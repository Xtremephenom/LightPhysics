#!/usr/bin/env node

import path from "node:path";
import { fileURLToPath } from "node:url";
import type { Writable } from "node:stream";
import { getBearerToken, loadConfig } from "@lightphysics/config";
import { createLogger } from "@lightphysics/logging";
import {
  LPD_VERSION,
  serverAddress,
  startServer,
  type LpdServer,
} from "@lightphysics/lpd";

const HELP = `Usage: lpd [--help]\n\nStarts the authenticated LightPhysics local daemon.\n\nEnvironment:\n  LP_TOKEN  Bearer token required by the daemon\n  LP_HOME   Application data directory\n  LP_BIND   Loopback bind address\n  LP_PORT   TCP port\n`;

export class LpdStartupError extends Error {
  readonly code = "MissingToken" as const;
  readonly suggestedNext = "Set LP_TOKEN in the environment and run lpd again.";

  constructor() {
    super("LP_TOKEN is required to start lpd; no bearer token is generated by the executable wrapper");
    this.name = "LpdStartupError";
  }
}

export interface LpdRunOptions {
  env?: NodeJS.ProcessEnv;
  stdout?: Writable;
  stderr?: Writable;
  installSignalHandlers?: boolean;
}

function write(stream: Writable | undefined, text: string): void {
  (stream ?? process.stdout).write(text);
}

function writeError(stream: Writable | undefined, error: unknown): void {
  if (error instanceof LpdStartupError) {
    write(
      stream ?? process.stderr,
      `${error.name} [${error.code}]: ${error.message}. ${error.suggestedNext}\n`,
    );
    return;
  }
  write(stream ?? process.stderr, `${error instanceof Error ? error.message : String(error)}\n`);
}

function formatHost(host: string): string {
  return host.includes(":") && !host.startsWith("[") ? `[${host}]` : host;
}

function closeServer(server: LpdServer): Promise<void> {
  if (!server.listening) return Promise.resolve();
  return new Promise((resolve, reject) => {
    server.close((error) => (error ? reject(error) : resolve()));
  });
}

function isMainModule(): boolean {
  const entry = process.argv[1];
  return entry !== undefined && path.resolve(entry) === fileURLToPath(import.meta.url);
}

export async function runLpd(
  argv: readonly string[] = process.argv.slice(2),
  options: LpdRunOptions = {},
): Promise<number> {
  const args = [...argv];
  while (args[0] === "--") args.shift();
  if (args.includes("--help") || args.includes("-h")) {
    write(options.stdout, HELP);
    return 0;
  }
  if (args.includes("--version") || args.includes("-v")) {
    write(options.stdout, `${LPD_VERSION}\n`);
    return 0;
  }
  if (args.length > 0) {
    write(options.stderr, "Unknown option. Use lpd --help.\n");
    return 2;
  }

  const env = options.env ?? process.env;
  const token = getBearerToken(env);
  if (!token) throw new LpdStartupError();

  // The executable wrapper deliberately keeps the daemon quiet except for its
  // non-secret endpoint. Request failures are still represented by the HTTP
  // response and do not turn the process stdout into a log channel.
  const config = loadConfig(env);
  const logger = createLogger({
    level: config.logLevel,
    format: config.logFormat,
    sink: () => undefined,
  });
  const server = await startServer({ env, token, logger });
  const address = serverAddress(server);
  if (!address) throw new Error("lpd did not expose a listening address");

  write(
    options.stdout,
    `lpd listening on ${formatHost(server.listenBind)}:${address.port}\n`,
  );

  let shuttingDown = false;
  let resolveShutdown: (() => void) | undefined;
  let rejectShutdown: ((error: unknown) => void) | undefined;
  const stopped = new Promise<void>((resolve, reject) => {
    resolveShutdown = resolve;
    rejectShutdown = reject;
  });
  const shutdown = (): void => {
    if (shuttingDown) return;
    shuttingDown = true;
    void server.killAll().then(() => closeServer(server)).then(
      () => resolveShutdown?.(),
      (error: unknown) => rejectShutdown?.(error),
    );
  };
  const installSignals = options.installSignalHandlers ?? true;
  if (installSignals) {
    process.once("SIGINT", shutdown);
    process.once("SIGTERM", shutdown);
  }
  try {
    await stopped;
  } finally {
    if (installSignals) {
      process.off("SIGINT", shutdown);
      process.off("SIGTERM", shutdown);
    }
  }
  return 0;
}

if (isMainModule()) {
  runLpd().then(
    (exitCode) => {
      process.exitCode = exitCode;
    },
    (error: unknown) => {
      writeError(undefined, error);
      process.exitCode = 1;
    },
  );
}
